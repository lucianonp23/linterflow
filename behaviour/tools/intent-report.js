#!/usr/bin/env node
/**
 * Builds behaviour/intent/INTENT_REPORT.md from the Jest JSON results of both arms.
 * Each test is classified by its outcome on the original (corpus) and the refactored
 * (corpus-run) file:
 *   pass/pass -> preserved   pass/fail -> REGRESSION   fail/pass -> fixed   fail/fail -> inherited
 */
const fs = require('fs');
const path = require('path');
const dir = path.join(__dirname, '..', 'intent', 'results');
const read = (arm) => JSON.parse(fs.readFileSync(path.join(dir, `${arm}.json`), 'utf8'));

function outcomes(json) {
  const m = new Map();
  for (const file of json.testResults) {
    for (const t of file.assertionResults) m.set(t.fullName, { file: t.ancestorTitles[0], title: t.title, status: t.status });
  }
  return m;
}
const orig = outcomes(read('corpus'));
const ref = outcomes(read('corpus-run'));
const CLASS = { 'passed/passed': 'preserved', 'passed/failed': 'REGRESSION', 'failed/passed': 'fixed', 'failed/failed': 'inherited' };

const rows = [];
for (const [name, o] of orig) {
  const r = ref.get(name);
  rows.push({ ...o, orig: o.status, ref: r ? r.status : 'missing', cls: CLASS[`${o.status}/${r && r.status}`] || '?', kind: (o.title.match(/^\[(\w+)\]/) || [])[1] });
}
const order = ['service_high_1', 'dto_high_4', 'middleware_high_1', 'middleware_high_3', 'dto_high_2', 'controller_high_3', 'middleware_high_2', 'repository_high_1'];
rows.sort((a, b) => order.indexOf(a.file) - order.indexOf(b.file));

const count = (f) => rows.filter(f).length;
const mark = (s) => (s === 'passed' ? 'pass' : 'FAIL');
let md = `# Intent-based tests: original vs refactored\n\n`;
md += `Generated by \`node behaviour/tools/intent-report.js\` from \`behaviour/intent/results/{corpus,corpus-run}.json\`.\n\n`;
md += `| | Tests | preserved | REGRESSION | fixed | inherited |\n|---|---:|---:|---:|---:|---:|\n`;
for (const k of ['ANCHOR', 'TARGET', 'IDEAL']) {
  const f = (x) => x.kind === k;
  md += `| ${k} | ${count(f)} | ${count((x) => f(x) && x.cls === 'preserved')} | ${count((x) => f(x) && x.cls === 'REGRESSION')} | ${count((x) => f(x) && x.cls === 'fixed')} | ${count((x) => f(x) && x.cls === 'inherited')} |\n`;
}
md += `| **Total** | ${rows.length} | ${count((x) => x.cls === 'preserved')} | ${count((x) => x.cls === 'REGRESSION')} | ${count((x) => x.cls === 'fixed')} | ${count((x) => x.cls === 'inherited')} |\n\n`;
md += `ANCHOR = ordinary behaviour of the file, expected to hold in both versions (checks the tests themselves).\n`;
md += `TARGET = the input on which the golden-master suite found a difference.\n`;
md += `IDEAL = the stricter handling the prompt asks for ("every edge case explicit"); a FAIL in both is a defect inherited from generation.\n\n`;
for (const f of order) {
  md += `## ${f}\n\n| Test | Original | Refactored | Class |\n|---|---|---|---|\n`;
  for (const r of rows.filter((x) => x.file === f)) md += `| ${r.title.replace(/\|/g, '\\|')} | ${mark(r.orig)} | ${mark(r.ref)} | ${r.cls} |\n`;
  md += `\n`;
}
fs.writeFileSync(path.join(__dirname, '..', 'intent', 'INTENT_REPORT.md'), md);
console.log(md.split('\n').slice(0, 12).join('\n'));

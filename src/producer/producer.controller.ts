import {
  Controller,
  Post,
  Get,
  Body,
  HttpCode,
  HttpStatus,
  Logger,
  UseGuards,
} from '@nestjs/common';
import {
  ApiTags,
  ApiOperation,
  ApiAcceptedResponse,
  ApiOkResponse,
  ApiBearerAuth,
  ApiForbiddenResponse,
} from '@nestjs/swagger';
import { ProducerService } from './producer.service';
import { OrchestrateDto } from './dto/orchestrate.dto';
import { ReporterService } from '../reporter/reporter.service';
import { PipelineBillingService } from '../credits/pipeline-billing.service';
import { JwtAuthGuard } from '../auth/guards/jwt-auth.guard';
import { AppEnvironmentService } from '../core/app-environment.service';
import { CurrentUser } from '../auth/decorators/current-user.decorator';
import type { AuthPrincipal } from '../users/user.types';

@ApiTags('orchestrator')
@ApiBearerAuth()
@Controller('api/orchestrator')
@UseGuards(JwtAuthGuard)
export class ProducerController {
  private readonly logger = new Logger(ProducerController.name);

  constructor(
    private readonly producerService: ProducerService,
    private readonly reporterService: ReporterService,
    private readonly billingService: PipelineBillingService,
    private readonly appEnvironment: AppEnvironmentService,
  ) {}

  /**
   * POST /api/orchestrator/start
   * Prices the run, charges the account's credits upfront (admins are
   * unlimited) and triggers the LinterFlow refactoring pipeline.
   */
  @Post('start')
  @HttpCode(HttpStatus.ACCEPTED) // Returns a 202 Accepted, not a 201 Created or 200 OK
  @ApiOperation({
    summary: 'Start the refactoring pipeline (staging only)',
    description:
      'Scans the target directory, charges the run cost in credits (1 per medium file, more for long files) and runs the self-healing loop (Evaluator → Feedback → Gemini) on every .ts file. Returns immediately (202) while processing continues in the background. Fails with 402 when the account balance does not cover the cost, and with 403 when APP_ENV is not staging — analysis by local path is refused in production, where only the GitHub import route is served.',
  })
  @ApiForbiddenResponse({
    description:
      'Analysis by local path is disabled in this deployment (APP_ENV is not staging).',
  })
  @ApiAcceptedResponse({
    description: 'Orchestration accepted and started in the background.',
    schema: {
      example: {
        status: 'PROCESSING',
        message: 'LinterFlow orchestration started successfully in the background.',
        targetDirectory: './mock-code',
        timestamp: '2026-06-04T10:00:00.000Z',
        runId: 'a3a4e6c0-…',
        filesFound: 4,
        creditsCharged: 5,
        creditsRemaining: 7,
      },
    },
  })
  public async startOrchestration(
    @Body() dto: OrchestrateDto,
    @CurrentUser() principal: AuthPrincipal,
  ) {
    // 0. Refuse before anything else — before logging the path, before pricing
    //    and before a run record exists. In production this route would be
    //    remote arbitrary file read and write: the pipeline sends every file it
    //    finds to Gemini and writes the answer back over the original.
    this.appEnvironment.assertLocalPathAnalysisAllowed();

    this.logger.log(`Received API request to orchestrate directory: ${dto.targetDirectory}`);

    // 1. Price the run and charge the account before any processing starts.
    const authorized = await this.billingService.authorizeRun(
      principal,
      'local',
      dto.targetDirectory,
      dto.targetDirectory,
    );

    // 2. Kick off the orchestration asynchronously.
    // Notice we do NOT use 'await' here. If we awaited this, the HTTP request
    // would hang until all files are processed, potentially causing a timeout.
    // orchestrateFolder never rejects (it catches internally), so the .then
    // always records the finished report on the run's history entry.
    this.producerService
      .orchestrateFolder(dto.targetDirectory)
      .then(() =>
        this.billingService.completeRun(
          authorized.run.id,
          this.reporterService.generateReport(),
        ),
      )
      .catch((error) => {
        this.logger.error(`Critical failure in background orchestration: ${error.message}`);
      });

    // 3. Immediately return a success acknowledgment to the client
    return {
      status: 'PROCESSING',
      message: 'LinterFlow orchestration started successfully in the background.',
      targetDirectory: dto.targetDirectory,
      timestamp: new Date().toISOString(),
      runId: authorized.run.id,
      filesFound: authorized.estimate.files.length,
      creditsCharged: authorized.creditsCharged,
      creditsRemaining: authorized.creditsRemaining,
    };
  }

  /**
   * GET /api/orchestrator/report
   * Returns the latest mitigation report generated by the ReporterService.
   */
  @Get('report')
  @ApiOperation({
    summary: 'Get the latest mitigation report',
    description:
      'Returns the accumulated pre/post metrics for every file processed in the most recent orchestration run.',
  })
  @ApiOkResponse({
    description: 'Mitigation report with per-file deltas and global statistics.',
  })
  public getReport() {
    return this.reporterService.generateReport();
  }
}
